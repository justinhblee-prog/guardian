import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "shared/filter_rules.txt");
const output = resolve(root, "chrome-extension/rules.txt");
const text = await readFile(source, "utf8");
const lines = text.split(/\\r?\\n/);
const rules = [];
for (const [index, raw] of lines.entries()) {
  const line = raw.trim();
  if (!line || line.startsWith("#")) continue;
  if (!/^(block|allow)=[a-z0-9.-]+$/i.test(line)) {
    throw new Error(`Unsupported shared rule at line ${index + 1}: ${line}`);
  }
  rules.push(line.toLowerCase());
}
if (rules.length === 0) throw new Error("Shared filter rule source is empty");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, [
  "# Generated from shared/filter_rules.txt by scripts/build_chrome_extension.mjs",
  "# Do not edit this file directly.",
  ...rules,
  ""
].join("\\n"));
console.log(`Generated ${rules.length} Chrome MV3 rules from shared/filter_rules.txt`);
